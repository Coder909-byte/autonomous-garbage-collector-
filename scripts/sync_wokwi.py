#!/usr/bin/env python3
"""Generate a standalone Wokwi sketch from the canonical, host-tested sources."""
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
body = '// GENERATED by scripts/sync_wokwi.py; edit canonical sources instead.\n'
for name in ('include/rover_control.h', 'include/rover_pins.h', 'include/rover_telemetry.h', 'firmware/rover.ino'):
    data = (root / name).read_text()
    data = data.replace('#pragma once\n', '')
    data = data.replace('#include "rover_control.h"\n', '').replace('#include "rover_pins.h"\n', '').replace('#include "rover_telemetry.h"\n', '').replace('#include "rover_control.h"\n', '')
    body += f'\n// Source: {name}\n' + data
out = root / 'wokwi/sketch.ino'
if '--check' in sys.argv:
    if out.read_text() != body:
        sys.exit('Wokwi sketch is stale: run python3 scripts/sync_wokwi.py')
    print('Wokwi sketch matches canonical sources')
else:
    out.write_text(body)
