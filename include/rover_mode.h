#pragma once

// Compile-time selection only. No serial/dashboard command can change this.
#define PROTECTED_ROVER 1
#define USB_BENCH_DIAGNOSTIC 2
#define MOTOR_OPERATION 3
#ifndef ROVER_OPERATING_MODE
#define ROVER_OPERATING_MODE PROTECTED_ROVER
#endif
#if ROVER_OPERATING_MODE != PROTECTED_ROVER && ROVER_OPERATING_MODE != USB_BENCH_DIAGNOSTIC && ROVER_OPERATING_MODE != MOTOR_OPERATION
#error Unknown ROVER_OPERATING_MODE
#endif

#include "rover_commissioning.h"

namespace rover {
constexpr bool MOTOR_OPERATION_MODE = ROVER_OPERATING_MODE == MOTOR_OPERATION;
constexpr bool PHYSICAL_FEEDBACK_REQUIRED = ROVER_OPERATING_MODE == PROTECTED_ROVER;
constexpr bool MOTOR_CAPABLE = ROVER_OPERATING_MODE != USB_BENCH_DIAGNOSTIC;
constexpr bool MOTOR_OUTPUTS_ALLOWED = MOTOR_CAPABLE && (!MOTOR_OPERATION_MODE || COMMISSIONING_READY);
constexpr const char *OPERATING_MODE = MOTOR_OPERATION_MODE ? "MOTOR_OPERATION" : MOTOR_CAPABLE ? "PROTECTED_ROVER" : "USB_BENCH_DIAGNOSTIC";
}
